// Derives src/features/earth/data/borders-data.ts from Natural Earth admin-0 (public domain) as redistributed in
// the `world-atlas` npm package (ISC): `npm pack world-atlas && tar xzf world-atlas-*.tgz`, then
//   node scripts/build-earth-borders.mjs path/to/package/countries-50m.json [tolerance_deg] [units_per_deg]
// TopoJSON arcs are shared edges, so an arc used by one country is a coastline and an arc used by two is a land border.
// Polylines are Douglas-Peucker simplified, quantised and stored as zig-zag varints (base64).
import { readFileSync, writeFileSync } from 'node:fs'

const [file, tolArg, qArg] = process.argv.slice(2)
const TOL = Number(tolArg ?? 0.04) // degrees
const Q = Number(qArg ?? 50) // units per degree
const topo = JSON.parse(readFileSync(file, 'utf8'))
const { scale, translate } = topo.transform

const arcs = topo.arcs.map((a) => {
  let x = 0, y = 0
  return a.map(([dx, dy]) => { x += dx; y += dy; return [x * scale[0] + translate[0], y * scale[1] + translate[1]] })
})
const uses = new Array(arcs.length).fill(0)
const visit = (a) => { if (Array.isArray(a)) a.forEach(visit); else uses[a < 0 ? ~a : a]++ }
for (const g of topo.objects.countries.geometries) visit(g.arcs)

function dp(pts, tol) {
  const keep = new Uint8Array(pts.length)
  keep[0] = keep[pts.length - 1] = 1
  const stack = [[0, pts.length - 1]]
  while (stack.length) {
    const [i, j] = stack.pop()
    let best = -1, bi = -1
    const [ax, ay] = pts[i], [bx, by] = pts[j]
    const dx = bx - ax, dy = by - ay, L2 = dx * dx + dy * dy
    for (let k = i + 1; k < j; k++) {
      const [px, py] = pts[k]
      let t = L2 ? ((px - ax) * dx + (py - ay) * dy) / L2 : 0
      t = Math.max(0, Math.min(1, t))
      const d = Math.hypot(px - (ax + t * dx), py - (ay + t * dy))
      if (d > best) { best = d; bi = k }
    }
    if (best > tol) { keep[bi] = 1; stack.push([i, bi], [bi, j]) }
  }
  return pts.filter((_, k) => keep[k])
}

const zz = (n) => (n << 1) ^ (n >> 31)
function varint(out, n) { n = zz(n) >>> 0; while (n >= 0x80) { out.push((n & 0x7f) | 0x80); n >>>= 7 } out.push(n) }
function encode(lines) {
  const out = []
  varint(out, lines.length)
  let pts = 0
  for (const l of lines) {
    const q = l.map(([x, y]) => [Math.round(x * Q), Math.round(y * Q)])
    // drop consecutive duplicates after quantisation
    const u = q.filter((p, i) => i === 0 || p[0] !== q[i - 1][0] || p[1] !== q[i - 1][1])
    if (u.length < 2) { varint(out, 0); continue }
    varint(out, u.length); pts += u.length
    let px = 0, py = 0
    for (const [x, y] of u) { varint(out, x - px); varint(out, y - py); px = x; py = y }
  }
  return { b64: Buffer.from(out).toString('base64'), bytes: out.length, pts }
}

const coast = [], border = []
arcs.forEach((a, i) => {
  if (a.length < 2) return
  const s = a.length > 2 ? dp(a, TOL) : a
  // Antimeridian cuts in the source (lon = ±180 straight lines) are not real borders
  if (s.every(([x]) => Math.abs(Math.abs(x) - 180) < 1e-6)) return
  ;(uses[i] > 1 ? border : coast).push(s)
})
const c = encode(coast), b = encode(border)
const ts = `// GENERATED by scripts/build-earth-borders.mjs from Natural Earth admin-0 countries (public domain) via the world-atlas npm package (ISC).
// ${file.split('/').pop()}, Douglas-Peucker ${TOL}°, quantised to 1/${Q}°, zig-zag varint + base64 (decoded in borders.ts).
export const BORDER_UNITS_PER_DEG = ${Q}
export const COAST_B64 = '${c.b64}'
export const BORDER_B64 = '${b.b64}'
`
writeFileSync(new URL('../src/features/earth/data/borders-data.ts', import.meta.url), ts)
console.log({ coastLines: coast.length, coastPts: c.pts, coastBytes: c.bytes, borderLines: border.length, borderPts: b.pts, borderBytes: b.bytes, fileBytes: ts.length })
